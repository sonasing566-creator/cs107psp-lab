
# Q16: Arithmetic Operators - Percentage Calculator

mark1 = 85.0
mark2 = 78.5
mark3 = 99.0

# Total and percentage
total = mark1 + mark2 + mark3
percentage = total / 300 * 100

print("Total Marks:", total)
print("Percentage:", percentage)

# //, %, **
print("Integer marks (//):", total // 1)
print("Remainder marks (%):", total % 1)
print("Square of percentage (**):", percentage ** 2)

# Arithmetic operators for two numbers
a = 20
b = 6

print("\nArithmetic Operators")
print("--------------------")
print("Operator   Result")
print("+          ", a + b)
print("-          ", a - b)
print("*          ", a * b)
print("/          ", a / b)
print("//         ", a // b)
print("%          ", a % b)
print("**         ", a ** b)
